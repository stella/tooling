import { createHash } from "node:crypto";

import type { resolveCloudToolchains } from "./cloud-setup-toolchains";

export const cloudShellProfilePath = "/etc/profile.d/stll-cloud.sh";
export const cloudShellProfileSource = `. ${cloudShellProfilePath}`;

const quote = (value: string) => `'${value.replaceAll("'", "'\\''")}'`;
type CloudShellOptions = {
  nodeVersion: string;
  bunVersion: string;
  rust: ReturnType<typeof resolveCloudToolchains>["rust"];
};

export const renderCloudShellProfile = ({
  nodeVersion,
  bunVersion,
  rust,
}: CloudShellOptions) => {
  const node = `/opt/stll-cloud/node/${nodeVersion}/bin`;
  const bun = `/opt/stll-cloud/bun/${bunVersion}`;
  return `# Generated by stll-cloud-setup; managed cloud shell environment.
# Remove managed entries before prepending, including repeated shell startup.
_stll_cloud_remaining="\${PATH-}"
_stll_cloud_result=''
_stll_cloud_separator=''
while :; do
  case "$_stll_cloud_remaining" in
    *:*) _stll_cloud_part="\${_stll_cloud_remaining%%:*}"; _stll_cloud_remaining="\${_stll_cloud_remaining#*:}"; _stll_cloud_more=yes ;;
    *) _stll_cloud_part="$_stll_cloud_remaining"; _stll_cloud_more=no ;;
  esac
  case "$_stll_cloud_part" in
    ${quote(node)}|${quote(bun)}|/usr/local/bin) ;;
    *) _stll_cloud_result="$_stll_cloud_result$_stll_cloud_separator$_stll_cloud_part"; _stll_cloud_separator=: ;;
  esac
  [ "$_stll_cloud_more" = yes ] || break
done
export PATH=${quote(`${node}:${bun}:/usr/local/bin`)}"\${_stll_cloud_separator:+:}$_stll_cloud_result"
unset _stll_cloud_remaining _stll_cloud_result _stll_cloud_separator _stll_cloud_part _stll_cloud_more
${rust === undefined ? "" : `export RUSTUP_HOME=/opt/stll-cloud/rustup\nexport CARGO_HOME=/opt/stll-cloud/cargo\nexport RUSTUP_TOOLCHAIN=${quote(rust.channel)}\nexport RUSTUP_AUTO_INSTALL=0\n`}`;
};

const userStartup = String.raw`
set -euo pipefail
for name in .bashrc .profile .bash_profile .bash_login; do
  file="$HOME/$name"
  if [[ ! -e "$file" && ! -L "$file" && "$name" != .bashrc && "$name" != .profile ]]; then continue; fi
  [[ ! -L "$file" ]] || { echo "cloud-setup: shell startup file must not be a symlink: $name" >&2; exit 1; }
  if [[ -e "$file" ]]; then
    [[ -f "$file" && "$(stat -c '%h:%u' "$file")" == "1:$(id -u)" ]] || { echo "cloud-setup: shell startup file must be owned and single-link: $name" >&2; exit 1; }
  fi
  temporary="$(mktemp "$HOME/.stll-cloud-shell.XXXXXX")"
  trap 'rm -f -- "$temporary"' EXIT
  if [[ "$name" == .bashrc ]]; then
    printf '%s\n' '# stll-cloud: early environment' '@SOURCE@' > "$temporary"
  fi
  if [[ -f "$file" ]]; then
    # Remove only exact managed blocks; preserve unrelated startup lines and permissions.
    awk '
      $0 == "# stll-cloud: early environment" || $0 == "# stll-cloud: session environment" {
        if ((getline following) <= 0 || following != "@SOURCE@") exit 1
        next
      }
      { print }
    ' "$file" >> "$temporary" || { echo "cloud-setup: managed shell startup block differs: $name" >&2; exit 1; }
  fi
  printf '%s\n' '# stll-cloud: session environment' '@SOURCE@' >> "$temporary"
  if [[ -f "$file" ]] && cmp -s "$temporary" "$file"; then rm -- "$temporary"; continue; fi
  if [[ -f "$file" ]]; then chmod --reference="$file" "$temporary"; else chmod 644 "$temporary"; fi
  mv -f -- "$temporary" "$file"
done
`;

export const renderCloudShellInstall = (options: CloudShellOptions) => {
  const profile = renderCloudShellProfile(options);
  return `install_shell_environment() (
  # Subshell scope retains temporary for EXIT cleanup after a failed command.
  [[ ! -L ${quote(cloudShellProfilePath)} ]] || fail 'Managed shell profile must not be a symlink'
  if [[ -e ${quote(cloudShellProfilePath)} ]]; then
    [[ -f ${quote(cloudShellProfilePath)} && "$(stat -c '%h:%u' ${quote(cloudShellProfilePath)})" == 1:0 ]] || fail 'Managed shell profile must be a root-owned single-link file'
  fi
  temporary="$(mktemp)"
  trap 'rm -f -- "$temporary"' EXIT
  cat > "$temporary" <<'STLL_CLOUD_PROFILE'
${profile}STLL_CLOUD_PROFILE
  if ! cmp -s "$temporary" ${quote(cloudShellProfilePath)}; then install -m 644 "$temporary" ${quote(cloudShellProfilePath)}; fi
  runuser -u "$OUTPUT_USER" -- env HOME="$OUTPUT_HOME" bash -c ${quote(userStartup.replaceAll("@SOURCE@", cloudShellProfileSource))}
)
verify_shell_environment() {
  [[ -f ${quote(cloudShellProfilePath)} && ! -L ${quote(cloudShellProfilePath)} && "$(stat -c '%h:%u' ${quote(cloudShellProfilePath)})" == 1:0 ]] || fail 'Managed shell environment is unavailable; run install'
  [[ "$(sha256sum -- ${quote(cloudShellProfilePath)} | cut -d ' ' -f1)" == ${quote(createHash("sha256").update(profile).digest("hex"))} ]] || fail 'Managed shell environment differs; run install'
}
`;
};
