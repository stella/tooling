// Offline and time-bounded: stdin is closed so a prompt cannot hold the
// snapshot. timeout leads its own process group (its pid), but it stops
// escalating once its direct child exits, so whatever is left in that group
// afterwards (a descendant that ignored TERM) is killed unconditionally.
const renderPrepare = (
  prepare: { script: string; seconds: number } | undefined,
  files: Readonly<Record<string, string>>,
) => {
  if (prepare === undefined) return "";
  const manifest = files["package.json"];
  if (manifest === undefined)
    throw new Error("cloud.prepare requires a tracked root package.json");
  const parsed: unknown = JSON.parse(manifest);
  const scripts =
    typeof parsed === "object" && parsed !== null && "scripts" in parsed
      ? parsed.scripts
      : undefined;
  if (
    typeof scripts !== "object" ||
    scripts === null ||
    !Object.hasOwn(scripts, prepare.script) ||
    typeof Reflect.get(scripts, prepare.script) !== "string"
  )
    throw new Error(
      `cloud.prepare.script ${prepare.script} is not a root package script`,
    );
  return [
    "prepare_sources() {",
    "  local leader status=0",
    `  timeout --kill-after=10 ${prepare.seconds} runuser -u "$OUTPUT_USER" -- env HOME="$OUTPUT_HOME" PATH="$PATH" "$BUN_DIR/bun" run ${shellQuote(prepare.script)} </dev/null &`,
    "  leader=$!",
    '  wait "$leader" || status=$?',
    '  kill -KILL -- "-$leader" 2>/dev/null || true',
    '  return "$status"',
    "}",
  ].join("\n");
};

export const generateCloudSetup = ({
  policy,
  cloud,
  nodeVersion,
  files = {},
  rustExceptions = [],
}: GenerateCloudSetupOptions) => {
  const selected = parseCloudSetup(cloud);
  if (selected === undefined) throw new Error("cloud declaration is required");
  const exactNode = nodeVersion.trim();
  if (
    valid(exactNode) !== exactNode ||
    !nodeSelectorMatches(exactNode, policy.node)
  )
    throw new Error(
      "cloud requires a tracked exact .node-version within the shared Node series",
    );
  let bunVersion = policy.bun;
  const manifest = files["package.json"];
  if (manifest !== undefined) {
    const parsed: unknown = JSON.parse(manifest);
    if (
      typeof parsed === "object" &&
      parsed !== null &&
      "packageManager" in parsed
    ) {
      const manager = parsed.packageManager;
      if (typeof manager === "string" && manager.startsWith("bun@"))
        bunVersion = manager.slice(4);
    }
  }
  const nodeArchiveSha256 = policy.nodeArchiveSha256[exactNode];
  if (nodeArchiveSha256 === undefined)
    throw new Error(`cloud Node ${exactNode} has no archive SHA256 pins`);
  const bunArchiveSha256 = policy.bunArchiveSha256[bunVersion];
  if (bunArchiveSha256 === undefined)
    throw new Error(
      `cloud packageManager Bun ${bunVersion} has no archive SHA256 pins; policy Bun is ${policy.bun}`,
    );
  const toolchains = resolveCloudToolchains({
    cloud: selected,
    files,
    rust: policy.rust,
    rustExceptions,
  });
  const services = cloudServices.filter((service) =>
    selected.services.includes(service),
  );
  const replacements = new Map([
    ["@INSTALL_ARGS@", selected.install.replace(/^bun /, "")],
    ["@NETWORK@", renderCloudNetwork()],
    [
      "@TOOL_INSTALL@",
      renderCloudToolInstall(toolchains) +
        renderCloudShellInstall({
          nodeVersion: exactNode,
          bunVersion,
          rust: toolchains.rust,
        }),
    ],
    [
      "@INPUT_VALIDATION@",
      ["rust-toolchain.toml", "rust-toolchain"]
        .flatMap((file) => {
          const content = files[file];
          if (content === undefined)
            return [
              `[[ ! -e ${shellQuote(file)} && ! -L ${shellQuote(file)} ]] || fail ${shellQuote(`${file} appeared; regenerate cloud-setup.sh`)}`,
            ];
          const hash = createHash("sha256").update(content).digest("hex");
          return [
            `[[ -f ${shellQuote(file)} && ! -L ${shellQuote(file)} ]] && [[ "$(sha256sum -- ${shellQuote(file)} | cut -d ' ' -f1)" == ${shellQuote(hash)} ]] || fail ${shellQuote(`${file} changed; regenerate cloud-setup.sh`)}`,
          ];
        })
        .concat(
          selected.tools?.["wasm-bindgen-cli"] === undefined
            ? []
            : [
                renderWasmBindgenLockValidation(
                  selected.tools["wasm-bindgen-cli"],
                ),
              ],
        )
        .join("\n"),
    ],
    ["@BUN@", bunVersion],
    ["@NODE@", exactNode],
    ["@NODE_AMD64_SHA@", nodeArchiveSha256.amd64],
    ["@NODE_ARM64_SHA@", nodeArchiveSha256.arm64],
    ["@BUN_AMD64_SHA@", bunArchiveSha256.amd64],
    ["@BUN_ARM64_SHA@", bunArchiveSha256.arm64],
    [
      "@ENV_ASSIGNMENTS@",
      selected.envFile === undefined
        ? ""
        : `ENV_FILE=${shellQuote(selected.envFile)}\nENV_MARKER=${shellQuote(cloudEnvironmentMarker)}`,
    ],
    [
      "@ENV_FUNCTIONS@",
      selected.envFile === undefined ? "" : environmentFunctions,
    ],
    [
      "@ENVIRONMENT_VALUES@",
      selected.services.length === 0 ? "" : environmentValuesFunction,
    ],
    [
      "@ENV_INITIALIZE@",
      selected.services.length === 0
        ? ""
        : "DATABASE_URL=''\nPOSTGRES_HOST=''\nPOSTGRES_USER=''\nPOSTGRES_PASSWORD=''\nPOSTGRES_DB_NAME=''\nPOSTGRES_ADDITIONAL_CONNECTION_DATA=''\nREDIS_URL=''",
    ],
    [
      "@ENV_VALIDATE@",
      selected.envFile === undefined ? "" : "validate_environment",
    ],
    [
      "@SESSION_ENVIRONMENT@",
      selected.services.length === 0 ? "" : sessionEnvironmentFunction,
    ],
    [
      "@SESSION_ENVIRONMENT_CALL@",
      selected.services.length === 0
        ? ""
        : 'if [[ "$MODE" == session ]]; then emit_session_environment; fi',
    ],
    ["@ENV_WRITE@", selected.envFile === undefined ? "" : "write_environment"],
    ["@PREPARE_FUNCTION@", renderPrepare(selected.prepare, files)],
    [
      "@PREPARE_STEP@",
      selected.prepare === undefined ? "" : "  step prepare prepare_sources",
    ],
    [
      "@SERVICE_INSTALL@",
      renderCloudServiceInstall({
        services,
        postgres: policy.postgres,
        valkey: policy.valkey,
        valkeyArtifacts: policy.valkeyArtifacts,
      }),
    ],
    [
      "@SERVICE_START@",
      renderCloudServiceStart({
        services,
        postgres: policy.postgres,
        valkey: policy.valkey,
      }),
    ],
  ]);
  const rendered = script.replace(/@[A-Z0-9_]+@/g, (token) => {
    const value = replacements.get(token);
    if (value === undefined)
      throw new Error(`Missing cloud setup field: ${token}`);
    return value;
  });
  return `${rendered.replace(/[ \t]+$/gm, "").trimEnd()}\n`;
};
