export const cloudEnvironmentMarker =
  "# Generated by stll-cloud-setup; disposable local test services.";

type GenerateCloudSetupOptions = {
  policy: ReturnType<typeof parseToolchainPolicy>;
  cloud: NonNullable<ReturnType<typeof parseCloudSetup>>;
  nodeVersion: string;
  files?: Readonly<Record<string, string>>;
  rustExceptions?: readonly RustException[];
};

const script = String.raw`#!/usr/bin/env bash
# Generated by stll-cloud-setup. Regenerate with stll-cloud-setup.
# Networked installation and offline service startup are separate lifecycle steps.
# Cached filesystems may not preserve processes; run start at every session start.
# Supported platform: Ubuntu 24.04 (noble), amd64/arm64, root or passwordless sudo.
set -euo pipefail

usage() { echo 'Usage: cloud-setup.sh install|start' >&2; exit 2; }
[[ "$#" == 1 ]] || usage
case "$1" in install|start) MODE="$1" ;; *) usage ;; esac
fail() { echo "cloud-setup: $*" >&2; exit 1; }
trap 'echo "cloud-setup: command failed at line $LINENO" >&2' ERR
# Each phase logs its start and duration so a stalled phase is visible in the task log.
step() {
  local name="$1" started="$SECONDS"
  shift
  echo "cloud-setup: $name started" >&2
  "$@"
  echo "cloud-setup: $name done in $((SECONDS - started))s" >&2
}
[[ -f /etc/os-release ]] || fail 'Ubuntu 24.04 is required'
. /etc/os-release
[[ "$ID" == ubuntu && "$VERSION_ID" == 24.04 && "$VERSION_CODENAME" == noble ]] || fail 'Only Ubuntu 24.04 (noble) is supported'
SCRIPT="$(realpath -- "$0")"
REPO_ROOT="$(cd -- "$(dirname -- "$SCRIPT")/.." && pwd -P)"
[[ "$SCRIPT" == "$REPO_ROOT/.agents/cloud-setup.sh" ]] || fail 'Run the generated repository script'
if [[ "$(id -u)" != 0 ]]; then
  command -v sudo >/dev/null && sudo -n true || fail 'Root or passwordless sudo is required'
  exec sudo -n -- bash "$SCRIPT" "$MODE"
fi
OUTPUT_UID="$(printenv SUDO_UID || id -u)"
[[ "$OUTPUT_UID" =~ ^[0-9]+$ ]] || fail 'Invalid invoking user'
OUTPUT_GID="$(getent passwd "$OUTPUT_UID" | cut -d: -f4)"
[[ "$OUTPUT_GID" =~ ^[0-9]+$ ]] || fail 'Invoking user is unavailable'
OUTPUT_USER="$(getent passwd "$OUTPUT_UID" | cut -d: -f1)"
OUTPUT_HOME="$(getent passwd "$OUTPUT_UID" | cut -d: -f6)"
[[ -n "$OUTPUT_USER" && "$OUTPUT_HOME" == /* && -d "$OUTPUT_HOME" ]] || fail 'Invoking user requires an existing home directory'
root() { "$@"; }
# Service daemons outlive setup, so they inherit no descriptor beyond stdio: a cloud
# runner can pass its terminal as extra descriptors and wait until every copy closes.
service_run() (
  for descriptor in "/proc/$BASHPID/fd/"*; do
    descriptor="$(basename -- "$descriptor")"
    if [[ "$descriptor" =~ ^[0-9]+$ ]] && (( descriptor > 2 )); then eval "exec $descriptor>&-"; fi
  done
  exec runuser -u stll-cloud -- "$@"
)
BUN_VERSION='@BUN@'
NODE_VERSION='@NODE@'
NODE_DIR="/opt/stll-cloud/node/$NODE_VERSION"
BUN_DIR="/opt/stll-cloud/bun/$BUN_VERSION"
export PATH="$NODE_DIR/bin:$BUN_DIR:/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"
BUN_CACHE="/var/cache/stll-cloud/bun/$OUTPUT_UID"
@ENV_ASSIGNMENTS@
[[ -f "$REPO_ROOT/.node-version" && ! -L "$REPO_ROOT/.node-version" ]] || fail 'A regular root .node-version is required'
[[ "$(awk 'NF { if (++count > 1 || NF != 1) exit 1; value=$1 } END { if (count != 1) exit 1; print value }' "$REPO_ROOT/.node-version")" == "$NODE_VERSION" ]] || fail 'Node selector changed; regenerate cloud-setup.sh'
cd -- "$REPO_ROOT"
case "$(uname -m)" in
  x86_64) ARCH=amd64; NODE_ARCH=x64; BUN_ARCH=x64 ;;
  aarch64|arm64) ARCH=arm64; NODE_ARCH=arm64; BUN_ARCH=aarch64 ;;
  *) fail 'Only amd64 and arm64 are supported' ;;
esac

@NETWORK@

runtime_ready() {
  [[ -x "$NODE_DIR/bin/node" && "$($NODE_DIR/bin/node --version)" == "v$NODE_VERSION" ]] || fail 'Pinned Node is unavailable; run install'
  [[ -x "$BUN_DIR/bun" && "$($BUN_DIR/bun --version)" == "$BUN_VERSION" ]] || fail 'Pinned Bun is unavailable; run install'
}
install_runtimes() {
  if ! command -v curl >/dev/null || ! command -v unzip >/dev/null || ! command -v xz >/dev/null || ! command -v openssl >/dev/null || ! command -v gpg >/dev/null || ! ldconfig -p | awk '$1 == "libatomic.so.1" { found=1 } END { exit !found }'; then
    apt_refresh_for ca-certificates curl unzip xz-utils openssl gnupg util-linux libatomic1
    DEBIAN_FRONTEND=noninteractive apt_install ca-certificates curl unzip xz-utils openssl gnupg util-linux libatomic1
  fi
  local scratch node_archive bun_archive bun_folder
  scratch="$(mktemp -d)"
  trap 'rm -rf -- "$scratch"' RETURN
  if [[ ! -x "$NODE_DIR/bin/node" ]] || [[ "$($NODE_DIR/bin/node --version)" != "v$NODE_VERSION" ]]; then
    node_archive="node-v$NODE_VERSION-linux-$NODE_ARCH.tar.xz"
    download_file "https://nodejs.org/dist/v$NODE_VERSION/$node_archive" "$scratch/$node_archive" 120
    download_file "https://nodejs.org/dist/v$NODE_VERSION/SHASUMS256.txt" "$scratch/node-sums" 45
    (cd "$scratch"; awk -v name="$node_archive" '$2 == name { print; count++ } END { if (count != 1) exit 1 }' node-sums | sha256sum --strict -c -)
    install -d -m 755 "$NODE_DIR"
    tar -xJf "$scratch/$node_archive" --strip-components=1 -C "$NODE_DIR"
  fi
  if [[ ! -x "$BUN_DIR/bun" ]] || [[ "$($BUN_DIR/bun --version)" != "$BUN_VERSION" ]]; then
    bun_folder="bun-linux-$BUN_ARCH"
    bun_archive="$bun_folder.zip"
    download_file "https://github.com/oven-sh/bun/releases/download/bun-v$BUN_VERSION/$bun_archive" "$scratch/$bun_archive" 120
    download_file "https://github.com/oven-sh/bun/releases/download/bun-v$BUN_VERSION/SHASUMS256.txt" "$scratch/bun-sums" 45
    (cd "$scratch"; awk -v name="$bun_archive" '$2 == name || $2 == "*" name { print $1 "  " name; count++ } END { if (count != 1) exit 1 }' bun-sums | sha256sum --strict -c -)
    unzip -q "$scratch/$bun_archive" -d "$scratch/bun"
    install -d -m 755 "$BUN_DIR"
    install -m 755 "$scratch/bun/$bun_folder/bun" "$BUN_DIR/bun"
  fi
  runtime_ready
  ln -sfnT -- "$NODE_DIR/bin/node" /usr/local/bin/node
  ln -sfnT -- "$NODE_DIR/bin/npm" /usr/local/bin/npm
  ln -sfnT -- "$NODE_DIR/bin/npx" /usr/local/bin/npx
  ln -sfnT -- "$BUN_DIR/bun" /usr/local/bin/bun
  rm -rf -- "$scratch"
  trap - RETURN
}

dependency_install() {
  local directory download_hosts
  for directory in /var/cache/stll-cloud /var/cache/stll-cloud/bun; do
    [[ ! -L "$directory" ]] || fail 'Dependency cache parent must not be a symlink'
    if [[ -e "$directory" ]]; then
      [[ -d "$directory" && "$(stat -c '%u' "$directory")" == 0 ]] || fail 'Dependency cache parent must be root-owned'
    fi
    install -d -m 755 -o root -g root "$directory"
  done
  [[ ! -L "$BUN_CACHE" ]] || fail 'Dependency cache must not be a symlink'
  if [[ -e "$BUN_CACHE" ]]; then
    [[ -d "$BUN_CACHE" && "$(stat -c '%u' "$BUN_CACHE")" == "$OUTPUT_UID" ]] || fail 'Dependency cache ownership differs from the invoking user'
  fi
  install -d -m 700 -o "$OUTPUT_UID" -g "$OUTPUT_GID" "$BUN_CACHE"
  # Report hostnames only: lockfile/config URLs may contain credentials.
  # These are known install hosts; lifecycle scripts can contact other hosts.
  download_hosts="$(HOME="$OUTPUT_HOME" "$NODE_DIR/bin/node" -e '
const fs = require("node:fs");
const path = require("node:path");
const hosts = new Set(["registry.npmjs.org"]);
const inputs = [process.env.BUN_CONFIG_REGISTRY ?? "", process.env.NPM_CONFIG_REGISTRY ?? "", process.env.npm_config_registry ?? ""];
for (const file of ["bun.lock", ".npmrc", "bunfig.toml", path.join(process.env.HOME, ".npmrc"), path.join(process.env.HOME, ".bunfig.toml"), path.join(process.env.XDG_CONFIG_HOME ?? process.env.HOME, ".bunfig.toml")]) {
  if (fs.existsSync(file)) inputs.push(fs.readFileSync(file, "utf8"));
}
for (const input of inputs) {
  for (const match of input.matchAll(/(?:git\+)?https?:\/\/[^\s"\x27<>\\]+/g)) {
    try { hosts.add(new URL(match[0].replace(/^git\+/, "")).hostname); } catch {}
  }
  if (/github:/.test(input)) { hosts.add("github.com"); hosts.add("codeload.github.com"); }
}
process.stdout.write([...hosts].sort().join(","));
')"
  # Bun 1.4.3 socket inactivity timeout, in seconds; the outer bound includes scripts.
  network_run "$download_hosts" 240 runuser -u "$OUTPUT_USER" -- env HOME="$OUTPUT_HOME" BUN_INSTALL_CACHE_DIR="$BUN_CACHE" PATH="$PATH" BUN_CONFIG_HTTP_IDLE_TIMEOUT=20 "$BUN_DIR/bun" @INSTALL_ARGS@
}

@SERVICE_INSTALL@
@SERVICE_START@

@TOOL_INSTALL@

@INPUT_VALIDATION@

@ENV_FUNCTIONS@

@PREPARE_FUNCTION@

if [[ "$MODE" == install ]]; then
  step runtimes install_runtimes
  step services install_services
  step tools install_tools
  step shell install_shell_environment
  step dependencies dependency_install
@PREPARE_STEP@
  exit 0
fi
step runtime-check runtime_ready
step tool-check verify_tools
step shell install_shell_environment
step shell-check verify_shell_environment
@ENV_VALIDATE@
step state prepare_state
step service-start start_services
@ENV_WRITE@
`;

const environmentFunctions = String.raw`
validate_environment() {
  local part target="$REPO_ROOT" env_path="$REPO_ROOT/$ENV_FILE" first_line temporary
  while IFS= read -r part; do
    target="$target/$part"
    [[ ! -L "$target" ]] || fail 'Environment path must not contain symbolic links'
  done < <(printf '%s\n' "$ENV_FILE" | tr '/' '\n')
  [[ -d "$(dirname -- "$env_path")" ]] || fail 'Environment parent directory is missing'
  if [[ -e "$env_path" ]]; then
    [[ -f "$env_path" ]] || fail 'Environment target must be a regular file'
    IFS= read -r first_line < "$env_path" || fail 'Refusing to overwrite an unowned environment file'
    [[ "$first_line" == "$ENV_MARKER" ]] || fail 'Refusing to overwrite an unowned environment file'
  fi
}
write_environment() {
  validate_environment
  local env_path="$REPO_ROOT/$ENV_FILE" temporary
  temporary="$(mktemp "$(dirname -- "$env_path")/.stll-cloud-env.XXXXXX")"
  chmod 600 "$temporary"
  {
    printf '%s\n' "$ENV_MARKER" 'NODE_ENV=test'
    if [[ -n "$DATABASE_URL" ]]; then printf 'DATABASE_URL=%s\n' "$DATABASE_URL"; fi
    if [[ -n "$REDIS_URL" ]]; then printf 'REDIS_URL=%s\n' "$REDIS_URL"; fi
  } > "$temporary"
  chown "$OUTPUT_UID:$OUTPUT_GID" "$temporary"
  mv -f -- "$temporary" "$env_path"
}
`;

const shellQuote = (value: string) => `'${value.replaceAll("'", "'\\''")}'`;

// Offline and time-bounded: stdin is closed so a prompt cannot hold the
// snapshot. timeout leads its own process group (its pid), but it stops
// escalating once its direct child exits, so whatever is left in that group
// afterwards (a descendant that ignored TERM) is killed unconditionally.
const renderPrepare = (
  prepare: { script: string; seconds: number } | undefined,
  files: Readonly<Record<string, string>>,
) => {
  if (prepare === undefined) return "";
  const manifest = files["package.json"];
  if (manifest === undefined)
    throw new Error("cloud.prepare requires a tracked root package.json");
  const parsed: unknown = JSON.parse(manifest);
  const scripts =
    typeof parsed === "object" && parsed !== null && "scripts" in parsed
      ? parsed.scripts
      : undefined;
  if (
    typeof scripts !== "object" ||
    scripts === null ||
    !Object.hasOwn(scripts, prepare.script) ||
    typeof Reflect.get(scripts, prepare.script) !== "string"
  )
    throw new Error(
      `cloud.prepare.script ${prepare.script} is not a root package script`,
    );
  return [
    "prepare_sources() {",
    "  local leader status=0",
    `  timeout --kill-after=10 ${prepare.seconds} runuser -u "$OUTPUT_USER" -- env HOME="$OUTPUT_HOME" PATH="$PATH" "$BUN_DIR/bun" run ${shellQuote(prepare.script)} </dev/null &`,
    "  leader=$!",
    '  wait "$leader" || status=$?',
    '  kill -KILL -- "-$leader" 2>/dev/null || true',
    '  return "$status"',
    "}",
  ].join("\n");
};

export const generateCloudSetup = ({
  policy,
  cloud,
  nodeVersion,
  files = {},
  rustExceptions = [],
}: GenerateCloudSetupOptions) => {
  const selected = parseCloudSetup(cloud);
  if (selected === undefined) throw new Error("cloud declaration is required");
  const exactNode = nodeVersion.trim();
  if (
    valid(exactNode) !== exactNode ||
    !nodeSelectorMatches(exactNode, policy.node)
  )
    throw new Error(
      "cloud requires a tracked exact .node-version within the shared Node series",
    );
  const toolchains = resolveCloudToolchains({
    cloud: selected,
    files,
    rust: policy.rust,
    rustExceptions,
  });
  const services = cloudServices.filter((service) =>
    selected.services.includes(service),
  );
  const replacements = new Map([
    ["@INSTALL_ARGS@", selected.install.replace(/^bun /, "")],
    ["@NETWORK@", renderCloudNetwork()],
    [
      "@TOOL_INSTALL@",
      renderCloudToolInstall(toolchains) +
        renderCloudShellInstall({
          nodeVersion: exactNode,
          bunVersion: policy.bun,
          rust: toolchains.rust,
        }),
    ],
    [
      "@INPUT_VALIDATION@",
      [
        "rust-toolchain.toml",
        "rust-toolchain",
        ...(selected.tools?.["wasm-bindgen-cli"] === undefined
          ? []
          : ["Cargo.lock"]),
      ]
        .flatMap((file) => {
          const content = files[file];
          if (content === undefined)
            return [
              `[[ ! -e ${shellQuote(file)} && ! -L ${shellQuote(file)} ]] || fail ${shellQuote(`${file} appeared; regenerate cloud-setup.sh`)}`,
            ];
          const hash = createHash("sha256").update(content).digest("hex");
          return [
            `[[ -f ${shellQuote(file)} && ! -L ${shellQuote(file)} ]] && [[ "$(sha256sum -- ${shellQuote(file)} | cut -d ' ' -f1)" == ${shellQuote(hash)} ]] || fail ${shellQuote(`${file} changed; regenerate cloud-setup.sh`)}`,
          ];
        })
        .join("\n"),
    ],
    ["@BUN@", policy.bun],
    ["@NODE@", exactNode],
    [
      "@ENV_ASSIGNMENTS@",
      selected.envFile === undefined
        ? ""
        : `ENV_FILE=${shellQuote(selected.envFile)}\nENV_MARKER=${shellQuote(cloudEnvironmentMarker)}`,
    ],
    [
      "@ENV_FUNCTIONS@",
      selected.envFile === undefined ? "" : environmentFunctions,
    ],
    [
      "@ENV_VALIDATE@",
      selected.envFile === undefined
        ? ""
        : "DATABASE_URL=''\nREDIS_URL=''\nvalidate_environment",
    ],
    ["@ENV_WRITE@", selected.envFile === undefined ? "" : "write_environment"],
    ["@PREPARE_FUNCTION@", renderPrepare(selected.prepare, files)],
    [
      "@PREPARE_STEP@",
      selected.prepare === undefined ? "" : "  step prepare prepare_sources",
    ],
    [
      "@SERVICE_INSTALL@",
      renderCloudServiceInstall({
        services,
        postgres: policy.postgres,
        valkey: policy.valkey,
        valkeyArtifacts: policy.valkeyArtifacts,
      }),
    ],
    [
      "@SERVICE_START@",
      renderCloudServiceStart({
        services,
        postgres: policy.postgres,
        valkey: policy.valkey,
      }),
    ],
  ]);
  return script.replace(/@[A-Z0-9_]+@/g, (token) => {
    const value = replacements.get(token);
    if (value === undefined)
      throw new Error(`Missing cloud setup field: ${token}`);
    return value;
  });
};
