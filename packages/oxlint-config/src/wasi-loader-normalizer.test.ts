import { expect, test } from "bun:test";
import assert from "node:assert/strict";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { basename, join } from "node:path";
import { fileURLToPath } from "node:url";

import {
  WASI_LOADER_TRANSFORMATIONS,
  normalizeGeneratedLoader,
  runWasiLoaderNormalizer,
} from "./wasi-loader-normalizer";

const fixtures = fileURLToPath(
  new URL("./__fixtures__/wasi-loaders/", import.meta.url),
);
const loaderNames = [
  "aho-corasick.wasi-browser.js",
  "aho-corasick.wasi.cjs",
] as const;

for (const name of loaderNames) {
  test(`${name} reproduces the committed aho-corasick normalized loader byte for byte`, async () => {
    const generated = await readFile(join(fixtures, name), "utf8");
    const committed = await readFile(
      join(fixtures, `${name}.normalized`),
      "utf8",
    );
    const normalized = normalizeGeneratedLoader(generated, {
      keepGeneratedTypecheckOptOut: true,
    });
    expect(normalized).toBe(committed);
    expect(
      normalizeGeneratedLoader(normalized, {
        keepGeneratedTypecheckOptOut: true,
      }),
    ).toBe(committed);
    expect(normalized.split("\n").at(0)).toBe(generated.split("\n").at(0));
    const headerLine = normalized.startsWith("// napi-rs-artifact-metadata:")
      ? 1
      : 0;
    expect(normalized.split("\n").at(headerLine)).toBe(
      "// @ts-nocheck -- generated by @napi-rs/cli",
    );
    expect(normalized).not.toMatch(/(?:eslint|prettier|biome)-disable/u);
    expect(normalized).toContain("function __invokeWasmCleanupPollScheduler(");
    expect(normalized).toContain("__emnapiWasmEnvCleanupPreparing = false");
  });
}

test("every normalized Worker construction uses identifier-backed workerData", async () => {
  for (const name of loaderNames) {
    const normalized = await readFile(
      join(fixtures, `${name}.normalized`),
      "utf8",
    );
    const constructionOffsets = [...normalized.matchAll(/new Worker\(/gu)].map(
      ({ index }) => index,
    );
    expect(constructionOffsets.length).toBeGreaterThan(0);
    for (const offset of constructionOffsets)
      expect(normalized.slice(offset, offset + 180)).toContain(
        "__workerOptions",
      );
    expect(normalized).toContain("workerData: __workerData");
  }
});

test("scheduler throws reject and reset cleanup so a retry can run", async () => {
  const source = await readFile(
    join(fixtures, "aho-corasick.wasi.cjs.normalized"),
    "utf8",
  );
  expect(source).toContain(
    "try {\n    schedule(finish)\n  } catch (error) {\n    reject(error)",
  );
  expect(source).toContain(
    "(error) => {\n      __emnapiWasmEnvCleanupPreparing = false\n      throw error",
  );
});

test("CLI writes both loaders and check mode detects drift", async () => {
  const root = await mkdtemp(join(tmpdir(), "wasi-normalizer-"));
  try {
    const paths = loaderNames.map((name) => join(root, basename(name)));
    await Promise.all(
      paths.map(async (path, index) =>
        writeFile(
          path,
          await readFile(join(fixtures, loaderNames[index]!), "utf8"),
        ),
      ),
    );
    await assert.rejects(
      runWasiLoaderNormalizer(["--check", ...paths]),
      /have drifted/u,
    );
    await runWasiLoaderNormalizer(paths);
    await runWasiLoaderNormalizer(["--check", ...paths]);
    for (const [index, path] of paths.entries())
      expect(await readFile(path, "utf8")).toBe(
        await readFile(
          join(fixtures, `${loaderNames[index]!}.normalized`),
          "utf8",
        ),
      );
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

for (const name of loaderNames) {
  for (const mode of ["write", "check"] as const) {
    test(`${mode} mode rejects CRLF ${name} with the transformation named`, async () => {
      const root = await mkdtemp(join(tmpdir(), "wasi-normalizer-crlf-"));
      const path = join(root, basename(name));
      try {
        const generated = await readFile(join(fixtures, name), "utf8");
        const crlf = generated.replaceAll("\n", "\r\n");
        await writeFile(path, crlf);
        const args = mode === "check" ? ["--check", path, path] : [path, path];
        await assert.rejects(
          runWasiLoaderNormalizer(args),
          new RegExp(`LF line endings.*${basename(name)}`, "u"),
        );
        expect(await readFile(path, "utf8")).toBe(crlf);
      } finally {
        await rm(root, { recursive: true, force: true });
      }
    });
  }
}

test("a missing generated anchor is rejected with the transformation and file named", async () => {
  const name = loaderNames[0];
  const generated = await readFile(join(fixtures, name), "utf8");
  const withoutAnchor = generated.replace(
    UNSAFE_CLEANUP_HANDSHAKE_FOR_TEST,
    "",
  );
  expect(withoutAnchor).not.toBe(generated);
  expect(() => normalizeGeneratedLoader(withoutAnchor, { file: name })).toThrow(
    new RegExp(`cleanup handshake.*${name}`, "u"),
  );
});

const UNSAFE_CLEANUP_HANDSHAKE_FOR_TEST = `await new Promise((resolve) => {
        __scheduleMacrotask(resolve)
      })`;

test("every changed transformation anchor is rejected in write and check modes", async () => {
  for (const transformation of WASI_LOADER_TRANSFORMATIONS) {
    for (const name of loaderNames) {
      const generated = await readFile(join(fixtures, name), "utf8");
      if (!generated.includes(transformation.anchor)) continue;

      for (const mode of ["write", "check"] as const) {
        const root = await mkdtemp(join(tmpdir(), "wasi-normalizer-anchor-"));
        const path = join(root, basename(name));
        try {
          const changed = generated.replace(
            transformation.anchor,
            `${transformation.anchor.slice(0, -1)} changed`,
          );
          expect(changed).not.toBe(generated);
          await writeFile(path, changed);
          const args =
            mode === "check" ? ["--check", path, path] : [path, path];
          await assert.rejects(
            runWasiLoaderNormalizer(args),
            new RegExp(`${transformation.name}.*${basename(name)}`, "u"),
          );
          expect(await readFile(path, "utf8")).toBe(changed);
        } finally {
          await rm(root, { recursive: true, force: true });
        }
      }
    }
  }
});
